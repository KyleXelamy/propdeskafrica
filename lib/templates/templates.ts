/* ─── Layout primitives ──────────────────────────────────────────────── */

const INK = "0F172A"
const MUTED = "64748B"
const FAINT = "94A3B8"
const RULE = "CBD5E1"
const TINT = "F1F5F9"

function p(text: string, opts: { bold?: boolean; size?: number; spacingAfter?: number; color?: string } = {}): Paragraph {
  return new Paragraph({
    spacing: { after: opts.spacingAfter ?? 120 },
    children: [new TextRun({ text, bold: opts.bold, size: opts.size ?? 22, color: opts.color ?? INK })],
  })
}

/** Small grey italic — used for hints, guidance and caveats. */
function hint(text: string, opts: { spacingAfter?: number; italic?: boolean } = {}): Paragraph {
  return new Paragraph({
    spacing: { after: opts.spacingAfter ?? 120 },
    children: [new TextRun({ text, italics: opts.italic ?? true, size: 18, color: MUTED })],
  })
}

function h1(text: string): Paragraph {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    spacing: { before: 160, after: 200 },
    children: [new TextRun({ text, bold: true, size: 30, color: "0369A1" })],
  })
}

function h2(text: string): Paragraph {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    spacing: { before: 280, after: 120 },
    children: [new TextRun({ text, bold: true, size: 24, color: INK })],
  })
}

/** A numbered clause body. Keeps legal numbering visible and citable. */
function clause(number: string, text: string): Paragraph {
  return new Paragraph({
    spacing: { after: 120 },
    indent: { left: 720, hanging: 720 },
    children: [
      new TextRun({ text: `${number}  `, bold: true, size: 21, color: INK }),
      new TextRun({ text, size: 21, color: INK }),
    ],
  })
}

function bullet(text: string): Paragraph {
  return new Paragraph({
    spacing: { after: 80 },
    indent: { left: 720, hanging: 360 },
    children: [
      new TextRun({ text: "•  ", bold: true, size: 21, color: MUTED }),
      new TextRun({ text, size: 21, color: INK }),
    ],
  })
}

function checkItem(text: string): Paragraph {
  return new Paragraph({
    spacing: { after: 70 },
    indent: { left: 360 },
    children: [
      new TextRun({ text: "☐   ", bold: true, size: 22, color: "0369A1" }),
      new TextRun({ text, size: 21, color: INK }),
    ],
  })
}

function fieldLine(label: string, value: string): Paragraph {
  return new Paragraph({
    spacing: { after: 80 },
    children: [
      new TextRun({ text: `${label}: `, bold: true, size: 22, color: INK }),
      new TextRun({ text: value || "—", size: 22, color: INK }),
    ],
  })
}

function dottedField(label: string): Paragraph {
  return new Paragraph({
    spacing: { after: 140 },
    children: [
      new TextRun({ text: `${label} `, bold: true, size: 21, color: INK }),
      new TextRun({ text: ".".repeat(70), size: 21, color: FAINT }),
    ],
  })
}

/** A boxed note for the reader — the "do this next" instruction. */
function actionBox(title: string, lines: string[]): Paragraph[] {
  return [
    new Paragraph({
      spacing: { before: 200, after: 60 },
      border: { top: { style: BorderStyle.SINGLE, size: 6, color: RULE, space: 6 } },
      children: [new TextRun({ text: title, bold: true, size: 20, color: INK })],
    }),
    ...lines.map(
      (t) =>
        new Paragraph({
          spacing: { after: 60 },
          children: [new TextRun({ text: t, size: 19, color: MUTED })],
        }),
    ),
    new Paragraph({
      spacing: { after: 160 },
      border: { bottom: { style: BorderStyle.SINGLE, size: 6, color: RULE, space: 6 } },
      children: [new TextRun({ text: "", size: 2 })],
    }),
  ]
}

function signatureRow(leftLabel: string, rightLabel: string): Table {
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: {
      top: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
      bottom: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
      left: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
      right: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
      insideHorizontal: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
      insideVertical: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
    },
    rows: [
      new TableRow({
        children: [
          new TableCell({
            width: { size: 50, type: WidthType.PERCENTAGE },
            children: [
              new Paragraph({ spacing: { before: 320 }, children: [new TextRun({ text: "_______________________________", size: 22 })] }),
              new Paragraph({ children: [new TextRun({ text: leftLabel, size: 18, color: MUTED })] }),
            ],
          }),
          new TableCell({
            width: { size: 50, type: WidthType.PERCENTAGE },
            children: [
              new Paragraph({ spacing: { before: 320 }, children: [new TextRun({ text: "_______________________________", size: 22 })] }),
              new Paragraph({ children: [new TextRun({ text: rightLabel, size: 18, color: MUTED })] }),
            ],
          }),
        ],
      }),
    ],
  })
}

