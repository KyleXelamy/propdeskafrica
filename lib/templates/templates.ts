/**
 * Real, designed templates for Kenyan landlords.
 *
 * Every template is generated via the `docx` library, so the output is a
 * proper Word file (.docx) that opens in Word, Pages, Google Docs, and
 * LibreOffice. Each template:
 *   - Has a clean header with "I-Manage · by Siemax Ltd" branding
 *   - Includes practical, Kenya-specific copy
 *   - Is designed for A4 paper, single-column, generous margins
 *   - Has signature blocks, dates, and a property/tenant-specific fill
 *
 * The template list lives in `templates` below; each entry describes the
 * template + a builder function. The same list powers the dashboard
 * `/dashboard/templates` page and the `/api/templates/[id]/docx` route.
 */
import {
  Document,
  Packer,
  Paragraph,
  TextRun,
  HeadingLevel,
  AlignmentType,
  Table,
  TableRow,
  TableCell,
  WidthType,
  BorderStyle,
  ShadingType,
  PageBreak,
  Header,
  Footer,
  PageNumber,
} from "docx"
import type { DocxTemplateInput, TemplateMeta } from "./types"

/* ─── Brand header used in every document ──────────────────────────── */
function brandHeader(label: string): Header {
  return new Header({
    children: [
      new Paragraph({
        alignment: AlignmentType.RIGHT,
        children: [
          new TextRun({ text: "I-Manage", bold: true, color: "0369A1", size: 20 }),
          new TextRun({ text: "  ·  by Siemax Ltd", color: "64748B", size: 16 }),
        ],
      }),
      new Paragraph({
        alignment: AlignmentType.RIGHT,
        children: [new TextRun({ text: label, italics: true, color: "94A3B8", size: 16 })],
      }),
    ],
  })
}

function brandFooter(): Footer {
  return new Footer({
    children: [
      new Paragraph({
        alignment: AlignmentType.CENTER,
        children: [
          new TextRun({
            text: "Generated by I-Manage · bknglabs.dev@gmail.com · Page ",
            color: "94A3B8",
            size: 16,
          }),
          new TextRun({ children: [PageNumber.CURRENT], color: "94A3B8", size: 16 }),
          new TextRun({ text: " of ", color: "94A3B8", size: 16 }),
          new TextRun({ children: [PageNumber.TOTAL_PAGES], color: "94A3B8", size: 16 }),
        ],
      }),
    ],
  })
}

function p(text: string, opts: { bold?: boolean; size?: number; spacingAfter?: number } = {}): Paragraph {
  return new Paragraph({
    spacing: { after: opts.spacingAfter ?? 120 },
    children: [new TextRun({ text, bold: opts.bold, size: opts.size ?? 22 })],
  })
}

function h1(text: string): Paragraph {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    spacing: { before: 240, after: 240 },
    children: [new TextRun({ text, bold: true, size: 32, color: "0369A1" })],
  })
}

function h2(text: string): Paragraph {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    spacing: { before: 200, after: 120 },
    children: [new TextRun({ text, bold: true, size: 26, color: "0F172A" })],
  })
}

function fieldLine(label: string, value: string): Paragraph {
  return new Paragraph({
    spacing: { after: 80 },
    children: [
      new TextRun({ text: `${label}: `, bold: true, size: 22 }),
      new TextRun({ text: value || "—", size: 22 }),
    ],
  })
}

function signatureRow(leftLabel: string, rightLabel: string): Table {
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: {
      top: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
      bottom: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
      left: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
      right: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
      insideHorizontal: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
      insideVertical: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
    },
    rows: [
      new TableRow({
        children: [
          new TableCell({
            width: { size: 50, type: WidthType.PERCENTAGE },
            children: [
              new Paragraph({ children: [new TextRun({ text: "_____________________", size: 22 })] }),
              new Paragraph({ children: [new TextRun({ text: leftLabel, size: 18, color: "64748B" })] }),
            ],
          }),
          new TableCell({
            width: { size: 50, type: WidthType.PERCENTAGE },
            children: [
              new Paragraph({ children: [new TextRun({ text: "_____________________", size: 22 })] }),
              new Paragraph({ children: [new TextRun({ text: rightLabel, size: 18, color: "64748B" })] }),
            ],
          }),
        ],
      }),
    ],
  })
}

function dottedField(label: string): Paragraph {
  const dots = "."
  return new Paragraph({
    spacing: { after: 80 },
    children: [
      new TextRun({ text: `${label} ${dots.repeat(60)}`, size: 22, color: "94A3B8" }),
    ],
  })
}

