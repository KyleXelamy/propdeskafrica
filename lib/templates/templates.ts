/**
 * Document templates for Kenyan landlords and property managers.
 *
 * Every template is generated via the `docx` library, so the output is a
 * proper Word file (.docx) that opens in Word, Pages, Google Docs, and
 * LibreOffice. Each template:
 *   - Has a clean header with "PropDesk Africa · by Siemax Ltd" branding
 *   - States the correct Kenyan statutory basis for what it does
 *   - Is designed for A4 paper, single-column, generous margins
 *   - Carries signature blocks, dates, and a property/tenant-specific fill
 *   - Ends with the specific next action the reader must take
 *
 * ── Legal basis (verified against current Kenyan law) ──────────────────
 * Residential tenancies in Kenya are NOT governed by the Landlord and Tenant
 * (Shops, Hotels and Catering Establishments) Act, Cap 301 — that Act applies
 * to shops, hotels and catering premises only. The correct framework is:
 *
 *   • Rent Restriction Act, Cap 296 — residential tenancies. Applies in full
 *     to "controlled tenancies" (standard rent not exceeding KShs 2,500 per
 *     month), administered by the Rent Restriction Tribunal. In practice the
 *     Tribunal and courts apply its principles more broadly.
 *   • Law of Contract Act, Cap 23 — governs above the controlled threshold,
 *     where the tenancy agreement is the primary source of obligations.
 *   • Distress for Rent Act, Cap 293 — recovery of rent arrears. Distress
 *     must be levied by a licensed auctioneer, never by a landlord or agent.
 *   • Land Act, section 57 — a tenant who remains in possession with consent
 *     after the term expires holds as a periodic tenant on the same period
 *     as the rent paid, and is entitled to one period's notice.
 *   • Data Protection Act, 2019 (No. 24 of 2019) — these forms collect
 *     national ID numbers and phone numbers, so section 29 duty-to-notify
 *     wording is included where personal data is captured.
 *
 * Consequence for late-payment clauses: Kenyan tribunals have struck down
 * punitive late-fee terms (see Tribunal Reference E153 of 2023, where
 * penalty charges were found unlawful and punitive). These templates use a
 * clearly-stated, proportionate interest that tracks actual loss instead of
 * an arbitrary flat percentage.
 *
 * These are drafting aids, not legal advice. They are deliberately explicit
 * about their limits so a user knows when to bring in an advocate.
 */
