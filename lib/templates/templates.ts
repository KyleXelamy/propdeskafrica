function headerCell(text: string, width: number): TableCell {
  return new TableCell({
    width: { size: width, type: WidthType.PERCENTAGE },
    shading: { fill: TINT, type: ShadingType.CLEAR, color: "auto" },
    children: [new Paragraph({ children: [new TextRun({ text, bold: true, size: 20, color: INK })] })],
  })
}

function bodyCell(text: string, width: number, opts: { color?: string; bold?: boolean } = {}): TableCell {
  return new TableCell({
    width: { size: width, type: WidthType.PERCENTAGE },
    children: [new Paragraph({ children: [new TextRun({ text, size: 20, color: opts.color ?? INK, bold: opts.bold })] })],
  })
}

/** Standard two-column label/value table. */
function kvTable(rows: Array<[string, string]>, labelWidth = 32): Table {
  return new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    rows: rows.map(
      ([k, v]) =>
        new TableRow({
          children: [
            new TableCell({
              width: { size: labelWidth, type: WidthType.PERCENTAGE },
              children: [new Paragraph({ children: [new TextRun({ text: k, bold: true, size: 20, color: INK })] })],
            }),
            new TableCell({
              width: { size: 100 - labelWidth, type: WidthType.PERCENTAGE },
              children: [new Paragraph({ children: [new TextRun({ text: v || "—", size: 20, color: INK })] })],
            }),
          ],
        }),
    ),
  })
}

function docPage(
  title: string,
  headerLabel: string,
  children: Paragraph[] | (Paragraph | Table)[],
  opts: { description?: string; pageBreakBefore?: boolean } = {},
): Document {
  return new Document({
    creator: "PropDesk Africa",
    title,
    description: opts.description ?? title,
    styles: { default: { document: { run: { font: "Calibri" } } } },
    sections: [
      {
        headers: { default: brandHeader(headerLabel) },
        footers: { default: brandFooter() },
        properties: { page: { margin: { top: 1080, right: 1080, bottom: 1080, left: 1080 } } },
        children: children as Paragraph[],
      },
    ],
  })
}

function today(): string {
  return new Date().toLocaleDateString("en-GB", { day: "2-digit", month: "long", year: "numeric" })
}

function monthYear(): string {
  return new Date().toLocaleDateString("en-GB", { month: "long", year: "numeric" })
}

