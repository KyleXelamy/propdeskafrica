export function getTemplate(id: string): TemplateMeta | null {
  return templates.find((t) => t.id === id) || null
}

export async function renderTemplate(id: string, input: DocxTemplateInput): Promise<Buffer> {
  const builder = builders[id]
  if (!builder) throw new Error(`Unknown template: ${id}`)
  const doc = builder(input)
  return await Packer.toBuffer(doc)
}

